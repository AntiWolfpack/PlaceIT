async function seed(): Promise<void> {
  await db.insert(vendorsTable).values(vendors).onConflictDoNothing({ target: vendorsTable.id });
  await db.insert(menuItemsTable).values(menuItems).onConflictDoNothing({ target: menuItemsTable.id });
  process.stdout.write(`Seeded ${vendors.length} vendors and ${menuItems.length} menu items.\n`);
}

seed()
  .catch((error: unknown) => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  })
  .finally(async () => {
    await pool.end();
  });